def ui_language() -> str:
    raw = os.environ.get("PLOTWEAVER_LANG", "en").lower()
    if raw in STRINGS:
        return raw
    return "en"


def tr(key: str, language: str | None = None) -> str:
    catalog = STRINGS[language or ui_language()]
    return catalog.get(key, STRINGS["en"][key])
